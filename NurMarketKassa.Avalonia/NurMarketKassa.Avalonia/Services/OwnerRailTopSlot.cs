namespace NurMarketKassa.Services;

/// <summary>2026-11-06, жалоба клиента (магазин одежды, Superwin): «слева кнопки почему перемещаются после нажатия». Причина: кнопка «»»
/// вверху тёмной колонки меню владельца пропадала (IsVisible) при нажатии на группу (колонка пунктов раскрывается) и появлялась снова
/// после выбора пункта — высота верха колонки менялась на ~44, ApplyRailDensity выбирал другую плотность, и значки прыгали (менялись
/// отступы, подписи). Теперь место под кнопку занято всегда (кнопка лишь прозрачная и не нажимается, когда колонка пунктов раскрыта) —
/// раскладка не зависит от того, раскрыта колонка пунктов или нет. Чистая логика без Avalonia — чтобы проверить тестом.</summary>
internal static class OwnerRailTopSlot
{
    /// <summary>Место под «»» занято в новом виде меню не на телефоне; у «Вкладок» вместо неё поиск (место тоже постоянное).</summary>
    public static bool ReservesSpace(bool phone, bool tabs) => !phone && !tabs;

    /// <summary>Кнопка «»» видна и нажимается только когда колонка пунктов свёрнута.</summary>
    public static bool ButtonShown(bool navItemsOpen, bool phone, bool tabs) => ReservesSpace(phone, tabs) && !navItemsOpen;
}
