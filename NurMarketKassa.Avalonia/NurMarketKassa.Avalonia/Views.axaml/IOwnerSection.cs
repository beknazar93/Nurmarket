using Avalonia;

namespace NurMarketKassa.AvaloniaHost.Views;

/// <summary>Окно кассы, которое программа владельца (OwnerShellWindow) встраивает разделом.
///
/// 2026-09-27, жалоба владельца «дублируется»: над разделом у программы владельца уже есть полоса
/// с его названием («Склад»), а сразу под ней окно рисовало свою крупную шапку с тем же названием
/// («Управление складом») и своей кнопкой «Закрыть» / ✕ / «Назад» / «Выход». AsOwnerSection
/// убирает только это — повтор названия и кнопки самого окна. Всё рабочее, что жило в той же
/// шапке (поиск, выгрузка в Excel/Word, «Обновить», период, подсказка про сканер…), остаётся
/// строкой инструментов. В кассе метод не вызывается, и окно выглядит как раньше.
///
/// Свои кнопки окна такой раздел прячет сам, поэтому общий поиск кнопок по классу
/// (OwnerShellWindow.PrepareEmbeddedWindow) его не трогает: тот поиск прятал и ✕ карточки
/// клиента, и закрыть карточку в программе владельца было нечем.</summary>
public interface IOwnerSection
{
    /// <summary>Вызывается программой владельца один раз — сразу после создания окна, до показа.</summary>
    void AsOwnerSection();

    /// <summary>2026-10-20, доработка п. 9 аудита: есть несохранённое — оболочка не закрывает спрятанный раздел ради памяти.
    /// null (по умолчанию) — раздел не знает сам, оболочка следит за вводом общим признаком (UnsavedInputTracker).</summary>
    bool? HasUnsavedChanges => null;
}

/// <summary>2026-10-20, живой аудит (память 933 МБ / 1 165 МБ к концу): спрятанные разделы программа владельца теперь
/// закрывает (держит только несколько последних). Раздел, у которого закрытие потеряет работу (идёт звонок советника,
/// несохранённая приёмка или ревизия), отвечает true — тогда оболочка его не закрывает.</summary>
public interface IOwnerSectionKeepAlive
{
    bool KeepAliveWhenHidden { get; }
}

/// <summary>Общие размеры разделов программы владельца.</summary>
public static class OwnerSectionLayout
{
    /// <summary>Поля содержимого раздела: слева и справа — как у названия раздела в полосе
    /// программы владельца (24 px). Сверху 12 px: полоса с названием уже стоит над разделом, а в
    /// этом зазоре рисуется тонкая полоска загрузки окна (у неё отрицательный отступ вверх — при
    /// меньшем зазоре она ушла бы за край).</summary>
    public static Thickness Margin => new(24, 12, 24, 20);
}
