namespace NurMarketKassa.Services;

/// <summary>
/// 2026-11-12 (ТЗ «Сфера Канцтовары», КТ4): сезон для «Нур Советника». В сфере «Канцтовары» в сводку для ИИ идёт короткая часть: вид магазина
/// и сезон месяца — «к школе» (июль–сентябрь: тетради, ручки, рюкзаки, пеналы, дневники, папки), второе полугодие (январь), подготовка
/// (май–июнь: заказать заранее). Только текст-подсказка: деньги и остатки считает сервер, цифры здесь не выдумываются.
/// У других сфер части нет.
/// </summary>
public static class StationerySeason
{
    public const string SectionKey = "sphere-stationery";

    /// <summary>Название сезона месяца (для подписи и проверок): school | prepare | second-half | regular.</summary>
    public static string SeasonCode(int month) => month switch
    {
        7 or 8 or 9 => "school",
        5 or 6 => "prepare",
        1 => "second-half",
        _ => "regular",
    };

    /// <summary>Текст для ИИ на дату <paramref name="date"/>. Всегда содержит код сферы <c>stationery</c> и месяц.</summary>
    public static string Text(DateTime date)
    {
        var head = $"ВИД МАГАЗИНА: stationery («Канцтовары и книги»): штучная торговля без весов и сроков годности, пачки и коробки, наборы и списки к школе, опт школам и офисам. Сейчас {date:MMMM yyyy} (месяц {date.Month}). ";
        var season = SeasonCode(date.Month) switch
        {
            "school" => "СЕЗОН «К ШКОЛЕ» (июль–сентябрь, пик — август): ходовой школьный ассортимент — тетради, ручки и карандаши, рюкзаки и пеналы, дневники, папки и файлы, альбомы и краски, наборы первоклассника. Советуй проверять остатки школьного ассортимента, докупать ходовое, не оставлять пустых полок, предложить «Списки к школе» и опт школам и офисам.",
            "prepare" => "ПОДГОТОВКА К СЕЗОНУ «К ШКОЛЕ» (май–июнь): школьный сезон начнётся в июле — советуй заранее заказать тетради, ручки, рюкзаки, пеналы и папки, составить «Списки к школе» по классам и договориться с поставщиками о сроках.",
            "second-half" => "ВТОРОЕ ПОЛУГОДИЕ (январь): школьники докупают тетради, ручки, альбомы и расходники — проверь остатки и пополни ходовое.",
            _ => "ОБЫЧНЫЙ СЕЗОН: основной спрос — офисная бумага и расходники, книги, творчество; советуй следить за остатками бумаги А4 и ходовых товаров и заранее планировать закупку к сезону «к школе» (июль–сентябрь).",
        };
        return head + season + " Скидку «к школе» на категорию с датами считает сервер (в кассе её пока нет) — до этого только обычная скидка на чек вручную.";
    }

    /// <summary>Часть сводки для ИИ или null, если сфера не «Канцтовары».</summary>
    public static AiSection? SectionFor(DateTime date) =>
        MarketSpheres.IsStationery
            ? new AiSection(SectionKey, "Вид магазина и сезон", 0, Text(date))
            : null;
}
