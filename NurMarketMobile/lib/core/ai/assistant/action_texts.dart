/// Текст по ключу на языке [lang] (нет перевода — русский); `{имя}` заменяются из [p].
String am(String key, String lang, [Map<String, String> p = const {}]) {
  final l = _t[key];
  if (l == null) return key;
  var s = switch (lang) {
    'ky' => l[1],
    'uz' => l[2],
    'en' => l[3],
    'tr' => l[4],
    _ => l[0],
  };
  p.forEach((k, v) => s = s.replaceAll('{$k}', v));
  return s;
}

