// 2026-10-27 (поток Р-5, ревью Ск-1/9/10/11/12/14/15/16/18 мобилки): разбор накладных — многостраничная таблица, «Цена без НДС» — цена,
// «Количество в одном месте» не количество, цены только «с НДС», «Сумма скидки» не сумма строки, 11 цифр штрихкода, «(500)», «1.234.567».
import 'dart:convert';
import 'dart:typed_data';

import 'package:flutter_test/flutter_test.dart';
import 'package:nurmarket/core/invoice/invoice_parser.dart';

ParsedInvoice csv(List<String> rows) => InvoiceParser.parse(Uint8List.fromList(utf8.encode(rows.join('\n'))), fileName: 'inv.csv');

void main() {
  test('Ск-1: многостраничная накладная — «Итого по странице» не заканчивает таблицу, итог файла — последний «Всего»', () {
    final inv = csv([
      'Накладная № 55 от 27.10.2026',
      '№;Наименование;Ед;Количество;Цена;Сумма',
      '1;Молоко;шт;2;50;100',
      '2;Хлеб;шт;3;20;60',
      ';Итого по странице;;5;;160',
      '№;Наименование;Ед;Количество;Цена;Сумма',
      '1;2;3;4;5;6',
      '3;Сыр;шт;1;300;300',
      '4;Масло;шт;2;100;200',
      ';Итого по странице;;3;;500',
      ';Всего;;8;;660',
    ]);
    expect(inv.lines.map((l) => l.name), ['Молоко', 'Хлеб', 'Сыр', 'Масло']);
    expect(inv.fileTotal, 660);
    expect(inv.linesTotal(), 660);
  });

  test('Ск-9: «Цена без НДС» — это цена, а не ставка НДС; ставка берётся из своего столбца', () {
    final inv = csv([
      'Наименование;Ед;Количество;Цена без НДС;Ставка НДС;Сумма без НДС',
      'Молоко;шт;2;50;12%;100',
    ]);
    final l = inv.lines.single;
    expect(l.cost, 50);
    expect(l.vat, 12);
    expect(l.qty, 2);
  });

  test('Ск-10: ТОРГ-12 — количество берётся из «…масса нетто», а не из «Количество в одном месте»', () {
    final inv = csv([
      'Наименование;Единица измерения;Количество в одном месте;Количество (масса нетто);Цена;Сумма без учета НДС',
      'Сахар;кг;1;25;60;1500',
    ]);
    final l = inv.lines.single;
    expect(l.qty, 25, reason: 'не 1');
    expect(l.cost, 60);
  });

  test('Ск-12: только цены «с НДС» и известная ставка — закупка без НДС (цена ÷ (1 + ставка)), метка costFromGross', () {
    final inv = csv([
      'Наименование;Ед;Количество;Цена с НДС;Ставка НДС;Сумма с НДС',
      'Молоко;шт;2;112;12%;224',
    ]);
    final l = inv.lines.single;
    expect(l.cost, 100, reason: '112 / 1,12');
    expect(l.costGross, 112);
    expect(l.costFromGross, isTrue);
    // ставка неизвестна — цена как есть, но метка стоит (экран предупредит)
    final inv2 = csv([
      'Наименование;Ед;Количество;Цена с НДС;Сумма с НДС',
      'Молоко;шт;2;112;224',
    ]);
    expect(inv2.lines.single.cost, 112);
    expect(inv2.lines.single.costFromGross, isTrue);
  });

  test('Ск-10/18: «Сумма скидки» не принимается за сумму строки', () {
    final inv = csv([
      'Наименование;Ед;Количество;Цена;Сумма скидки;Сумма',
      'Молоко;шт;2;50;5;95',
    ]);
    final l = inv.lines.single;
    expect(l.sum, 95);
    expect(l.cost, 50);
  });

  test('Ск-16: штрихкод 11 цифр (Excel срезал ведущий 0) — достраивается до 12 при верной контрольной цифре; чужое не трогается', () {
    // 012345678905: UPC-A с верной контрольной цифрой 5 -> без 0: 12345678905 (11 цифр)
    final inv = csv([
      'Штрихкод;Наименование;Ед;Количество;Цена;Сумма',
      '12345678905;Молоко;шт;2;50;100',
      '12345678901;Хлеб;шт;1;20;20',
    ]);
    expect(inv.lines[0].barcode, '012345678905');
    expect(inv.lines[1].barcode, '12345678901', reason: 'контрольная цифра не сходится — не угадываем');
  });

  test('Ск-18: «(500)» = −500, «1.234.567» = 1 234 567, «1 234,5» = 1234,5', () {
    expect(parseInvoiceNumber('(500)'), -500);
    expect(parseInvoiceNumber('1.234.567'), 1234567);
    expect(parseInvoiceNumber('1 234,5'), 1234.5);
  });

  test('Ск-15: CommerceML «УчтеноВСумме = true» — цена и сумма уже с НДС: закупка без НДС = цена ÷ 1,12, «с НДС» НДС второй раз не прибавляет', () {
    const xml = '''<?xml version="1.0" encoding="UTF-8"?>
<КоммерческаяИнформация><Документ><Номер>9</Номер><Товары>
<Товар><Наименование>Молоко</Наименование><Штрихкод>4870200221261</Штрихкод><Количество>2</Количество><ЦенаЗаЕдиницу>112</ЦенаЗаЕдиницу><Сумма>224</Сумма>
<Налоги><Налог><Наименование>НДС</Наименование><УчтеноВСумме>true</УчтеноВСумме><Ставка>12</Ставка></Налог></Налоги></Товар>
</Товары></Документ></КоммерческаяИнформация>''';
    final inv = InvoiceParser.parse(Uint8List.fromList(utf8.encode(xml)), fileName: 'cml.xml');
    final l = inv.lines.single;
    expect(l.cost, 100);
    expect(l.costGross, 112);
    expect(l.unitCost(withVat: true), 112, reason: 'с НДС — 112, а не 125,44');
    expect(l.unitCost(), 100);
    expect(l.sum, 200);
    expect(l.sumGross, 224);
  });
}
