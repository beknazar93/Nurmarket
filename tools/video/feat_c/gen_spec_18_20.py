import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
EX = os.path.normpath(os.path.join(HERE, "..", "examples"))
COUNTER = {"x": 1470, "y": 705, "s": 0.85}
PH = [1130, 6, 740, 890]          # телефон справа
CY = {"bg": "#FFB208", "fg": "#191919", "size": 44}


def final():
    return {"type": "final", "dur": 4.0, "say": [{"who": "N", "at": 0.5, "text": "NurCRM — касса, которая знает ваш магазин.",
            "tts": "Нур Си-Эр-Эм — касса, которая знает ваш магазин.", "show": False, "maxdur": 3.1}]}


def N(at, text, maxdur, tts=None, sub=None):
    d = {"who": "N", "at": at, "text": text, "maxdur": maxdur}
    if tts:
        d["tts"] = tts
    if sub:
        d["sub"] = sub
    return d


def chip(text, x, y, at, dur, **k):
    d = {"text": text, "x": x, "y": y, "at": at, "dur": dur}
    d.update(CY)
    d.update(k)
    return d


def phone(src=None, clip=None, at=0, dur=5, crop=(0, 0, 1, 1), marks=(), frm=0, ln=0):
    v = {"at": at, "dur": dur, "crop": list(crop), "frame": "phone", "area": PH, "marks": list(marks)}
    if src:
        v["src"] = src
    else:
        v["clip"] = clip
        v["from"] = frm
        v["len"] = ln
    return v


def mk(at, rect, kind="click", dur=None):
    m = {"at": at, "kind": kind, "rect": list(rect)}
    if dur:
        m["dur"] = dur
    return m


def W(num, slug, title, scenes):
    for s in scenes:
        for b in s.get("boxes", []):
            if b["w"] <= 440:
                b.setdefault("tsize", 36)
                b.setdefault("size", 28)
    d = {"name": "feat-%02d-%s" % (num, slug.split("-", 1)[1]), "lang": "ru", "voice": "none", "music": False, "fps": 30,
         "feat": {"num": num, "total": 20, "slug": slug, "title": title, "scenes": scenes + [final()]}}
    with open(os.path.join(EX, "feat-%02d-%s.json" % (num, slug.split("-", 1)[1])), "w", encoding="utf-8") as f:
        json.dump(d, f, ensure_ascii=False, indent=1)
    print(num, "OK", sum(s["dur"] for s in scenes) + 4.0)


